// 시험 1 — 모델 정확도: 28x28 원본 화소를 그대로 넣고,
//          PyTorch가 냈던 출력값과 얼마나 차이 나는지 잰다.
// 시험 2 — 전체 경로: 28x28을 280x280 캔버스에 키워 그린 뒤
//          전처리부터 추론까지 실제 사용 흐름 그대로 돌려 정답률을 잰다.

import { 숫자인식모델 } from "./모델.js";
import { 전처리 } from "./전처리.js";

const 결과칸 = document.getElementById("결과");

function 적기(글) {
  결과칸.textContent += 글 + "\n";
}

function 최대값자리(배열) {
  let 최대 = -Infinity;
  let 자리 = -1;
  배열.forEach((값, 번호) => {
    if (값 > 최대) { 최대 = 값; 자리 = 번호; }
  });
  return 자리;
}

// 28x28 화소를 280x280 캔버스에 키워 그린다 (사람이 그린 것과 비슷한 상황을 만든다)
function 캔버스에_그리기(화소) {
  const 작은판 = document.createElement("canvas");
  작은판.width = 28;
  작은판.height = 28;
  const 작은맥락 = 작은판.getContext("2d");
  const 화상 = 작은맥락.createImageData(28, 28);
  for (let i = 0; i < 784; i++) {
    화상.data[i * 4] = 화소[i];
    화상.data[i * 4 + 1] = 화소[i];
    화상.data[i * 4 + 2] = 화소[i];
    화상.data[i * 4 + 3] = 255;
  }
  작은맥락.putImageData(화상, 0, 0);

  const 큰판 = document.createElement("canvas");
  큰판.width = 280;
  큰판.height = 280;
  const 큰맥락 = 큰판.getContext("2d", { willReadFrequently: true });
  큰맥락.drawImage(작은판, 0, 0, 280, 280);

  const 화상2 = 큰맥락.getImageData(0, 0, 280, 280);
  const 밝기 = new Float32Array(280 * 280);
  for (let i = 0; i < 밝기.length; i++) 밝기[i] = 화상2.data[i * 4];
  return 밝기;
}

(async () => {
  try {
    적기("모델과 검증 데이터를 불러오는 중…");
    const 모델 = await 숫자인식모델.불러오기();
    const 자료 = await (await fetch("검증데이터.json")).json();
    적기(`불러옴: 검증 이미지 ${자료.장수}장`);
    적기("");

    // ── 시험 1 ───────────────────────────────────────────
    적기("[시험 1] 파이썬 출력값과 대조 (28x28 원본 입력)");
    let 맞힌수 = 0;
    let 최대오차 = 0;
    let 예측불일치 = 0;

    for (const 항목 of 자료.항목) {
      const 로그확률 = 모델.화소로_추론(항목.화소);
      const 예측 = 최대값자리(로그확률);
      const 파이썬예측 = 최대값자리(항목.출력);

      if (예측 === 항목.정답) 맞힌수++;
      if (예측 !== 파이썬예측) 예측불일치++;
      for (let i = 0; i < 10; i++) {
        최대오차 = Math.max(최대오차, Math.abs(로그확률[i] - 항목.출력[i]));
      }
    }

    적기(`  정답률        : ${맞힌수}/${자료.장수} (${(100 * 맞힌수 / 자료.장수).toFixed(1)}%)`);
    적기(`  파이썬과 예측 : ${예측불일치 === 0 ? "전부 일치" : `${예측불일치}장 불일치`}`);
    적기(`  출력값 최대오차: ${최대오차.toExponential(3)}`);
    적기(`  판정          : ${예측불일치 === 0 && 최대오차 < 1e-3 ? "통과" : "실패"}`);
    적기("");

    // ── 시험 2 ───────────────────────────────────────────
    적기("[시험 2] 전체 경로 (280x280 캔버스 → 전처리 → 추론)");
    let 맞힌수2 = 0;
    let 빈그림 = 0;

    for (const 항목 of 자료.항목) {
      const 밝기 = 캔버스에_그리기(항목.화소);
      const 화소 = 전처리(밝기, 280, 280);
      if (!화소) { 빈그림++; continue; }
      const 예측 = 최대값자리(모델.화소로_추론(화소));
      if (예측 === 항목.정답) 맞힌수2++;
    }

    적기(`  정답률        : ${맞힌수2}/${자료.장수} (${(100 * 맞힌수2 / 자료.장수).toFixed(1)}%)`);
    적기(`  빈 그림 처리  : ${빈그림}장`);
    적기(`  판정          : ${맞힌수2 >= 자료.장수 * 0.94 ? "통과" : "실패"}`);
    적기("");
    적기("검증 종료");
  } catch (오류) {
    적기("");
    적기(`오류: ${오류.message}`);
    적기(오류.stack || "");
  }
})();
