"""바로가기와 앱 창에 쓸 아이콘(icon.ico)을 만든다.

앱의 그림판과 같은 분위기로, 어두운 둥근 사각형 위에 흰 손글씨 숫자를 얹는다.
여러 해상도(16~256px)를 한 파일에 담아 작업 표시줄·바탕화면 어디서든 또렷하게 보이게 한다.

사용법:
    python make_icon.py
"""

from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

아이콘_파일 = Path(__file__).parent / "icon.ico"

# 큰 크기로 그린 뒤 줄이면 가장자리가 매끄럽다
기준_크기 = 1024
배경색 = (24, 28, 40, 255)       # 짙은 남색
글자색 = (255, 255, 255, 255)    # 흰색
강조색 = (90, 160, 255, 255)     # 밑줄에 쓰는 파란색

# 손글씨 느낌의 윈도우 기본 글꼴
글꼴_경로 = r"C:\Windows\Fonts\segoesc.ttf"


def 아이콘_그리기() -> Image.Image:
    """1024x1024 아이콘 이미지를 그려서 돌려준다."""
    그림 = Image.new("RGBA", (기준_크기, 기준_크기), (0, 0, 0, 0))
    붓 = ImageDraw.Draw(그림)

    # 모서리가 둥근 사각형 배경
    여백 = 40
    붓.rounded_rectangle(
        [여백, 여백, 기준_크기 - 여백, 기준_크기 - 여백],
        radius=180, fill=배경색)

    # 가운데에 숫자 3을 크게 쓴다
    글꼴 = ImageFont.truetype(글꼴_경로, 620)
    왼쪽, 위, 오른쪽, 아래 = 붓.textbbox((0, 0), "3", font=글꼴)
    글자_x = (기준_크기 - (오른쪽 - 왼쪽)) / 2 - 왼쪽
    글자_y = (기준_크기 - (아래 - 위)) / 2 - 위 - 40  # 밑줄 자리만큼 살짝 위로
    붓.text((글자_x, 글자_y), "3", font=글꼴, fill=글자색)

    # 글씨를 쓴 줄을 나타내는 밑줄
    밑줄_y = 기준_크기 - 250
    붓.rounded_rectangle(
        [260, 밑줄_y, 기준_크기 - 260, 밑줄_y + 34],
        radius=17, fill=강조색)

    return 그림


def main():
    그림 = 아이콘_그리기()
    # 윈도우가 상황에 맞는 해상도를 골라 쓰도록 여러 크기를 함께 저장한다
    크기_목록 = [(16, 16), (24, 24), (32, 32), (48, 48), (64, 64), (128, 128), (256, 256)]
    그림.save(아이콘_파일, format="ICO", sizes=크기_목록)
    print(f"아이콘을 만들었습니다: {아이콘_파일}")


if __name__ == "__main__":
    main()
